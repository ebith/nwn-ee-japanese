"""Generates the font atlas tables from the TLK code point inventory.

The atlas slot of a character is its index in kNwnjpLegacyCodepoints, and
CAurFont::TextOut treats a glyph whose index ends in 0x3C (the ASCII '<') as the
start of markup, so no real character may sit on such a slot. A space is baked
in front of each of those slots to keep them unused.

The NUI font atlas is asked for `nk_rune` ranges instead of a code point list, so
the same inventory is emitted as ranges as well.

Usage: python src/nwnjp/generate-codepoint-tables.py
"""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
# The inventory lists the code points the Japanese TLK uses; it is the build input.
CODEPOINTS_TXT = ROOT / "src" / "nwnjp" / "tlk-codepoints.txt"
CODEPOINTS_H = ROOT / "src" / "nwnjp" / "legacy_codepoints.h"
SLOT_TABLE_H = ROOT / "src" / "nwnjp" / "codepoint_slot_table.h"
NUI_RANGE_H = ROOT / "src" / "nwnjp" / "nui_range_table.h"

# Character gaps this short are not worth a separate range: the atlas gains a few
# unused glyphs, and nuklear walks fewer ranges.
NUI_RANGE_GAP = 4

# Bytes 0x00..0xFF keep the original single byte mapping so existing text keeps
# its glyphs; undefined cp1252 positions stand for themselves.
CP1252 = {
    0x80: 0x20AC, 0x82: 0x201A, 0x83: 0x0192, 0x84: 0x201E, 0x85: 0x2026,
    0x86: 0x2020, 0x87: 0x2021, 0x88: 0x02C6, 0x89: 0x2030, 0x8A: 0x0160,
    0x8B: 0x2039, 0x8C: 0x0152, 0x8E: 0x017D, 0x91: 0x2018, 0x92: 0x2019,
    0x93: 0x201C, 0x94: 0x201D, 0x95: 0x2022, 0x96: 0x2013, 0x97: 0x2014,
    0x98: 0x02DC, 0x99: 0x2122, 0x9A: 0x0161, 0x9B: 0x203A, 0x9C: 0x0153,
    0x9E: 0x017E, 0x9F: 0x0178,
}

MARKUP_BYTE = 0x3C
PADDING = 0x20  # space; the duplicate slot is never used


def base_codepoints():
    return [CP1252.get(b, b) for b in range(256)]


def build_list():
    tlk = {int(token, 16) for token in CODEPOINTS_TXT.read_text(encoding="utf-8").split()}
    base = base_codepoints()
    taken = set(base)
    slots = list(base)
    for cp in sorted(cp for cp in tlk if cp not in taken):
        while len(slots) >= 256 and (len(slots) & 0xFF) == MARKUP_BYTE:
            slots.append(PADDING)
        slots.append(cp)
    return slots


def write_codepoints(codepoints):
    lines = [
        "// Generated by src/nwnjp/generate-codepoint-tables.py from tlk-codepoints.txt.",
        "// The first 256 entries keep the original byte to code point mapping so existing text",
        "// keeps its glyphs; the rest are additional dialogue characters, sorted, with a space",
        "// baked in front of every slot that would otherwise look like the '<' markup byte.",
        "#pragma once",
        "",
        f"static const unsigned int kNwnjpLegacyCodepoints[{len(codepoints)}] = {{",
    ]
    for i in range(0, len(codepoints), 12):
        chunk = ", ".join(f"0x{cp:X}" for cp in codepoints[i : i + 12])
        lines.append(f"    {chunk},")
    lines.append("};")
    lines.append("")
    CODEPOINTS_H.write_text("\n".join(lines), encoding="utf-8")


def write_slot_table(codepoints):
    table = [0xFFFF] * 0x10000
    for slot, cp in enumerate(codepoints):
        if cp < 0x10000 and table[cp] == 0xFFFF:
            table[cp] = slot
    lines = [
        "// Generated by src/nwnjp/generate-codepoint-tables.py from legacy_codepoints.h.",
        "// Unicode code point (0x0000..0xFFFF) to legacy atlas slot; 0xFFFF is not in the set.",
        "#pragma once",
        "#include <cstdint>",
        "",
        "static const uint16_t kNwnjpCodepointSlot[65536] = {",
    ]
    for i in range(0, len(table), 16):
        chunk = ", ".join(f"0x{value:04X}" for value in table[i : i + 16])
        lines.append(f"    {chunk},")
    lines.append("};")
    lines.append("")
    SLOT_TABLE_H.write_text("\n".join(lines), encoding="utf-8")


def nui_ranges(codepoints):
    """Merges the inventory into nuklear's (first, last) pairs, terminated by 0."""
    points = sorted(codepoints)
    pairs = []
    first = last = points[0]
    for cp in points[1:]:
        if cp - last <= NUI_RANGE_GAP:
            last = cp
        else:
            pairs.append((first, last))
            first = last = cp
    pairs.append((first, last))
    values = []
    for first, last in pairs:
        values.extend((first, last))
    values.extend((0, 0))
    return pairs, values


def write_nui_range_table(values):
    lines = [
        "// Generated by src/nwnjp/generate-codepoint-tables.py from tlk-codepoints.txt.",
        "// nk_rune pairs (first, last) terminated by 0, as nuklear expects.",
        "#pragma once",
        "",
        f"static const unsigned int kNwnjpNuiRangeTable[{len(values)}] = {{",
    ]
    for i in range(0, len(values), 8):
        chunk = ", ".join(f"0x{value:04X}" for value in values[i : i + 8])
        lines.append(f"    {chunk},")
    lines.append("};")
    lines.append("")
    NUI_RANGE_H.write_text("\n".join(lines), encoding="utf-8")


def main():
    codepoints = build_list()
    write_codepoints(codepoints)
    write_slot_table(codepoints)
    pairs, values = nui_ranges({int(token, 16) for token in CODEPOINTS_TXT.read_text(encoding="utf-8").split()})
    write_nui_range_table(values)
    padding = len(codepoints) - len(set(codepoints))
    print(f"entries: {len(codepoints)} (padding: {padding})")
    print(f"nui ranges: {len(pairs)} ({len(values)} values)")
    print(f"wrote {CODEPOINTS_H.relative_to(ROOT)}, {SLOT_TABLE_H.relative_to(ROOT)}"
          f" and {NUI_RANGE_H.relative_to(ROOT)}")


if __name__ == "__main__":
    main()


